// Writes backend/src/generated/build-info.ts with the current git commit + branch.
// Runs before tsc so the build embeds the exact source commit that produced dist/.
// Prefer Railway/Vercel build-provided env vars; fall back to local git.
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

function gitSafe(command) {
  try {
    return execSync(command, { cwd: path.resolve(__dirname, '..'), encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

const commit = process.env.RAILWAY_GIT_COMMIT_SHA
  || process.env.SOURCE_VERSION
  || process.env.VERCEL_GIT_COMMIT_SHA
  || gitSafe('git rev-parse --short HEAD');
const fullCommit = commit && commit.length >= 40 ? commit : gitSafe('git rev-parse HEAD');
const branch = process.env.RAILWAY_GIT_BRANCH
  || process.env.VERCEL_GIT_COMMIT_REF
  || gitSafe('git rev-parse --abbrev-ref HEAD');
const builtAt = new Date().toISOString();

const outDir = path.resolve(__dirname, '..', 'src', 'generated');
fs.mkdirSync(outDir, { recursive: true });

const content = `// AUTO-GENERATED by scripts/write-build-info.cjs — do not edit manually.
export const BUILD_COMMIT = ${JSON.stringify(commit)};
export const BUILD_FULL_COMMIT = ${JSON.stringify(fullCommit)};
export const BUILD_BRANCH = ${JSON.stringify(branch)};
export const BUILD_TIME = ${JSON.stringify(builtAt)};
`;

fs.writeFileSync(path.join(outDir, 'build-info.ts'), content);
console.log(`[build-info] commit=${commit} branch=${branch} builtAt=${builtAt}`);