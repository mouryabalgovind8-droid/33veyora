// Flatten all cities with their state info for search
export interface CitySuggestion {
  city: string;
  state: string;
  stateCode: string;
  label: string; // "Mumbai, Maharashtra"
}

export const allCities: CitySuggestion[] = indianStates.flatMap((s) =>
  s.cities.map((city) => ({
    city,
    state: s.name,
    stateCode: s.code,
    label: `${city}, ${s.name}`,
  }))
);

// Deduplicate cities (some states share city names)
const seen = new Set<string>();
export const uniqueCities: CitySuggestion[] = allCities.filter((c) => {
  const key = c.city.toLowerCase();
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

/**
 * Search Indian cities by partial input
 * "Mum" → Mumbai, Maharashtra
 * "Maha" → Maharashtra (state match)
 */
export function searchLocations(query: string): CitySuggestion[] {
  if (!query || query.length < 1) return [];
  const q = query.toLowerCase().trim();

  // First: match cities
  const cityMatches = uniqueCities.filter(
    (c) =>
      c.city.toLowerCase().includes(q) ||
      c.label.toLowerCase().includes(q)
  );

  // Second: match states — show all cities in matching states
  const stateMatches = uniqueCities.filter(
    (c) =>
      c.state.toLowerCase().includes(q) ||
      c.stateCode.toLowerCase() === q
  );

  // Merge and deduplicate
  const merged = new Map<string, CitySuggestion>();
  for (const c of [...cityMatches, ...stateMatches]) {
    merged.set(c.label, c);
  }

  return Array.from(merged.values()).slice(0, 8);
}

/**
 * Get all cities for a given state
 */
export function getCitiesForState(stateName: string): string[] {
  const state = indianStates.find(
    (s) => s.name.toLowerCase() === stateName.toLowerCase()
  );
  return state?.cities || [];
}

/**
 * Find state name from partial input
 * "Maha" → "Maharashtra"
 * "Ma" → ["Madhya Pradesh", "Maharashtra", "Manipur", "Meghalaya", "Mizoram"]
 */
export function searchStates(query: string): StateData[] {
  if (!query || query.length < 1) return [];
  const q = query.toLowerCase().trim();
  return indianStates.filter(
    (s) => s.name.toLowerCase().includes(q) || s.code.toLowerCase() === q
  );
}
